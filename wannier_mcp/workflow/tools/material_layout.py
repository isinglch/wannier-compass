#!/usr/bin/env python3
"""Create the standard per-material view without running or certifying science."""
import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile

FORMAT = 'wannier-material-layout-v1'
MARKER = '<!-- Generated by material_layout.py; keep personal notes in records/. -->\n'
CORE = {
    '01_scf': ('POSCAR', 'POTCAR', 'INCAR', 'KPOINTS', 'OUTCAR', 'CHGCAR'),
    '02_band': ('POSCAR', 'POTCAR', 'INCAR', 'KPOINTS', 'OUTCAR', 'EIGENVAL', 'PROCAR'),
}
OPTIONAL = ('run.json', 'charge.npz', 'fit_path.json')
REQUIRED_OUTPUTS = ('wannier90.win', 'wannier90.wout', 'wannier90.chk',
    'wannier90_hr.dat', 'wannier90_r.dat', 'wannier90_tb.dat',
    'wannier90_band.dat', 'wannier90_band.kpt')
OPTIONAL_OUTPUTS = ('wannier90_band.gnu', 'wannier90_band.agr',
    'wannier90_wsvec.dat', 'wannier90_centres.xyz')


def now():
    return datetime.now(timezone.utc).isoformat()


def sha(path):
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def inside(path, root):
    try:
        path.resolve().relative_to(root.resolve())
    except (ValueError, RuntimeError) as error:
        raise ValueError('Path or symlink escapes its allowed directory: ' + str(path)) from error


def local_path(root, *parts):
    """Managed paths may not traverse symlink directories, even inside root."""
    path = root
    for part in parts:
        path = path / part
        if path.is_symlink():
            raise ValueError('Managed directory/file must not be a symlink: ' + str(path))
        inside(path, root)
    return path


def source_file(path, allowed):
    inside(path, allowed)
    if not path.exists():
        return False
    if not path.is_file():
        raise ValueError('Expected a regular artifact: ' + str(path))
    return path.stat().st_size > 0


def write_json(path, record):
    if path.exists() or path.is_symlink():
        raise ValueError('Refusing to overwrite a record: ' + str(path))
    with path.open('x') as stream:
        json.dump(record, stream, ensure_ascii=False, indent=2)
        stream.write('\n')


def check_managed_readme(path):
    if path.is_symlink() or (path.exists() and not path.read_text().startswith(MARKER)):
        raise ValueError('Refusing to overwrite an unmanaged README: ' + str(path))


def write_readme(path, body):
    check_managed_readme(path)
    fd, name = tempfile.mkstemp(prefix='.layout-readme-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(MARKER + body)
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def case_paths(case):
    record = json.loads((case/'MATERIAL-LAYOUT.json').read_text())
    reused = record.get('mode', 'reused_dft') == 'reused_dft'
    return dict(case_dir=str(case), scf_dir=str(case/'01_scf'/('source' if reused else '')),
        band_dir=str(case/'02_band'/('source' if reused else '')), band_cache=str(case/'02_band/charge.npz'),
        band_path=str(case/'02_band/fit_path.json'),
        source_band_cache=str(case/'02_band/source/charge.npz') if reused else str(case/'02_band/charge.npz'),
        band_plots_dir=str(case/'02_band/plots'), trials_dir=str(case/'03_wan_trial'),
        initial_dir=str(case/'03_wan_trial/initial'), decision_index=str(case/'03_wan_trial/index.html'))


def case_readme(case):
    lines = ['# Material workspace', '',
        '- [01_scf](01_scf/README.md): current or reused SCF inputs, provenance, and core hashes.',
        '- [02_band](02_band/README.md): current or reused projected bands; figures in plots/.',
        '- [03_wan_trial](03_wan_trial/README.md): separate interface, disentanglement, and comparison trials.', '',
        'Directories and links organize evidence; they do not certify DFT convergence, disentanglement, or fit.', '',
        '- [Decision trajectory and selection figures](03_wan_trial/index.html): initial, real_first_try, and retries.',
        '- [Initial baseline](03_wan_trial/initial/STAGE.json): recorded without direct submission.', '', '## Trials', '']
    for path in sorted((case/'03_wan_trial').iterdir()):
        if path.is_dir() and not path.is_symlink() and re.fullmatch(r'trial_[0-9]{3,}', path.name):
            lines.append(f'- [{path.name}](03_wan_trial/{path.name}/README.md)')
    if lines[-1] == '':
        lines.append('No trials created yet.')
    return '\n'.join(lines) + '\n'


def load_case(path):
    case = Path(path).resolve()
    record_path = local_path(case, 'MATERIAL-LAYOUT.json')
    record = json.loads(record_path.read_text())
    if not isinstance(record, dict) or record.get('format') != FORMAT or record.get('case_dir') != str(case):
        raise ValueError('Material layout identity mismatch.')
    if record.get('mode', 'reused_dft') not in ('reused_dft', 'fresh_dft'):
        raise ValueError('Unsupported material layout mode.')
    for name in ('01_scf', '02_band', '03_wan_trial'):
        if not local_path(case, name).is_dir():
            raise ValueError('Missing managed stage: ' + name)
    return case


def register_fresh(case_dir):
    """Register 01/02 stages created by dft_workflow.prepare, without source links."""
    case = Path(case_dir).resolve()
    if not case.is_dir():
        raise ValueError('Fresh DFT case directory must already exist.')
    marker = local_path(case, 'MATERIAL-LAYOUT.json')
    if marker.exists():
        raise ValueError('Material layout already registered.')
    check_managed_readme(case/'README.md')
    for stage in ('01_scf','02_band','03_wan_trial'):
        directory = local_path(case, stage)
        if directory.exists() and not directory.is_dir():
            raise ValueError('Expected stage directory: '+str(directory))
        check_managed_readme(directory/'README.md')
        if stage in CORE and ((directory/'SOURCE.json').exists() or (directory/'SOURCE.json').is_symlink()):
            raise ValueError('Fresh source record already exists: '+stage)
    for stage in ('01_scf','02_band','03_wan_trial'):
        directory = case/stage; directory.mkdir(exist_ok=True)
        if stage in CORE:
            files = {}
            for name in ('POSCAR','POTCAR','INCAR','KPOINTS'):
                path = directory/name
                if source_file(path, directory):
                    files[name] = dict(sha256=sha(path), bytes=path.stat().st_size,
                                      resolved_path=str(path.resolve()))
            write_json(directory/'SOURCE.json', dict(format='dft-source-reference-v1',
                mode='fresh_dft_preparation_snapshot', source_dir=str(directory), recorded_utc=now(),
                files=files, scientific_validation='not_performed_by_layout_tool',
                completion_record='run.json after actual DFT execution'))
            body = f'# {stage}\n\nThis directory holds fresh DFT inputs and outputs, without a source link.\n\n'
            body += '[SOURCE.json](SOURCE.json) snapshots prepared inputs; the stage run.json records actual execution and output identity.\n'
            if stage=='02_band':
                body += '\nBand collection generates charge.npz, fit_path.json, and DFT/projected-band figures in plots/.\n'
        else:
            body = '# Wannier trials\n\nUse `decision_stages.py initial/select` for the baseline and selected trials; retain outputs inside each trial.\n'
        write_readme(directory/'README.md', body)
    write_json(marker, dict(format=FORMAT, mode='fresh_dft', case_dir=str(case),
        created_utc=now(), dft_manifest='case.json'))
    write_readme(case/'README.md', case_readme(case))
    return dict(status='fresh_dft_layout_registered', paths=case_paths(case), accepted=False)


def init(case_dir, scf_source, band_source):
    requested = Path(case_dir).absolute()
    if requested.exists() or requested.is_symlink():
        raise ValueError('case-dir must be a new directory.')
    case = requested.resolve()
    sources = {'01_scf': Path(scf_source).resolve(), '02_band': Path(band_source).resolve()}
    records = {}
    for stage, source in sources.items():
        if not source.is_dir():
            raise ValueError('Source directory does not exist: ' + str(source))
        files, missing = {}, []
        for name in (*CORE[stage], *OPTIONAL):
            path = source/name
            if source_file(path, source):
                before = path.stat(); digest = sha(path); after = path.stat()
                if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
                    raise ValueError('Source changed during hashing: ' + str(path))
                files[name] = dict(sha256=digest, bytes=after.st_size,
                                  resolved_path=str(path.resolve()))
            elif name in CORE[stage]:
                missing.append(name)
        records[stage] = dict(format='dft-source-reference-v1', source_dir=str(source),
            recorded_utc=now(), core_files=list(CORE[stage]), files=files,
            missing_core_files=missing, source_complete=not missing,
            scientific_validation='not_performed_by_layout_tool')
    case.mkdir(parents=True)
    for stage, source in sources.items():
        directory = case/stage
        directory.mkdir()
        (directory/'source').symlink_to(source, target_is_directory=True)
        write_json(directory/'SOURCE.json', records[stage])
        if stage == '02_band':
            for name in ('charge.npz','fit_path.json'):
                if name in records[stage]['files']:
                    (directory/name).symlink_to('source/'+name)
        write_readme(directory/'README.md', f'# {stage}\n\n'
            f'Reused DFT source: [source](source/); original absolute path: `{source}`.\n\n'
            'Core files and SHA256: [SOURCE.json](SOURCE.json). The source is read-only; write no new figures or edits there.\n\n'
            + ('Write the current band cache here and figures in [plots](plots/).\n\n' if stage=='02_band' else '')
            + 'Missing core files: ' + (', '.join(records[stage]['missing_core_files']) or 'none')
            + '. File completeness does not establish DFT convergence.\n')
    (case/'03_wan_trial').mkdir()
    write_readme(case/'03_wan_trial/README.md', '# Wannier trials\n\n'
        'Use `decision_stages.py initial/select` to seal the baseline and select trials. Each has records; official tools create interface, wannier, and comparison directories.\n')
    write_json(case/'MATERIAL-LAYOUT.json', dict(format=FORMAT, mode='reused_dft', case_dir=str(case),
        created_utc=now(), sources={k:str(v) for k,v in sources.items()}))
    write_readme(case/'README.md', case_readme(case))
    return dict(status='initialized', paths=case_paths(case),
        missing_core_files={k:v['missing_core_files'] for k,v in records.items()}, accepted=False)


def trial_path(case, trial_id):
    if not re.fullmatch(r'trial_[0-9]{3,}', trial_id):
        raise ValueError('trial-id must be trial_ followed by at least three digits, e.g. trial_001.')
    return local_path(case, '03_wan_trial', trial_id)


def trial_paths(case, trial):
    return dict(**case_paths(case), trial_dir=str(trial), interface_dir=str(trial/'interface'),
        wannier_dir=str(trial/'wannier'), comparison_dir=str(trial/'comparison'),
        records_dir=str(trial/'records'), selection_dir=str(trial/'records/selection'), analysis_path=str(trial/'records/selection/analysis.json'),
        decision_path=str(trial/'records/selection/decision.json'))


def new_trial(case_dir, trial_id):
    case = load_case(case_dir); trial = trial_path(case, trial_id)
    if trial.exists():
        raise ValueError('Trial already exists; use a new trial-id.')
    check_managed_readme(case/'README.md')
    trial.mkdir(); (trial/'records').mkdir()
    write_readme(trial/'README.md', f'# {trial_id}\n\nNot executed; scientific status unknown and unaccepted.\n\n'
        '- [selection](records/selection/): sealed analysis, decision, figures, and provenance.\n'
        '- [results](records/results/): actual execution and assessment snapshots.\n'
        '- interface/: official preparation followed by VASP execution.\n'
        '- wannier/: official preparation followed by disentanglement only.\n'
        '- comparison/: same-k interpolation, fit figures, and review evidence.\n\n'
        'After execution, use `material_layout.py publish` to refresh display links; directory creation is not scientific success.\n')
    write_readme(case/'README.md', case_readme(case))
    return dict(status='trial_created_not_executed', paths=trial_paths(case, trial), accepted=False)


def plan_link(plans, destination, source, allowed):
    if not source_file(source, allowed):
        return False
    relative = os.path.relpath(source, destination.parent)
    if destination.is_symlink():
        if os.readlink(destination) != relative or destination.resolve() != source.resolve():
            raise ValueError('Refusing to replace a link to a different target: ' + str(destination))
    elif destination.exists():
        raise ValueError('Refusing to replace an existing file: ' + str(destination))
    plans.append((destination, source, relative))
    return True


def publish(case_dir, trial_id):
    case = load_case(case_dir); trial = trial_path(case, trial_id)
    if not trial.is_dir():
        raise ValueError('Trial must first be created with new-trial.')
    wannier = local_path(case, '03_wan_trial', trial_id, 'wannier')
    comparison = local_path(case, '03_wan_trial', trial_id, 'comparison')
    plots = local_path(case, '02_band', 'plots')
    for path in (case/'README.md', trial/'README.md'):
        check_managed_readme(path)
    plans, missing = [], []
    for name in (*REQUIRED_OUTPUTS, *OPTIONAL_OUTPUTS):
        if not plan_link(plans, trial/name, wannier/name, wannier) and name in REQUIRED_OUTPUTS:
            missing.append('wannier/'+name)
    for suffix in ('png', 'pdf'):
        name = 'fit_review.'+suffix
        if not plan_link(plans, trial/name, comparison/name, comparison):
            missing.append('comparison/'+name)
    band_images = []
    if plots.exists():
        for source in sorted(plots.iterdir()):
            if source.suffix.lower() in ('.png', '.pdf'):
                if plan_link(plans, case/'02_band'/source.name, source, plots):
                    band_images.append(source.name)
    for name in ('dft_bands.png', 'dft_bands.pdf', 'projected_bands.png', 'projected_bands.pdf'):
        if name not in band_images:
            missing.append('02_band/plots/'+name)
    record_path = wannier/'wannier_run.json'
    state = {}
    if source_file(record_path, wannier):
        record = json.loads(record_path.read_text())
        if not isinstance(record, dict):
            raise ValueError('wannier_run.json must contain a JSON object.')
        state = {key:record.get(key) for key in ('status','num_iter','execution_complete',
            'disentanglement','fit_status','fit_pass','accepted')}
    else:
        missing.append('wannier/wannier_run.json')
    for destination, source, relative in plans:
        if not destination.is_symlink():
            destination.symlink_to(relative)
    lines = [f'# {trial_id}', '',
        '**Display inventory: '+('incomplete' if missing else 'display_complete')+'; publishing links does not establish scientific acceptance.**', '',
        '## Scientific status (read from wannier/wannier_run.json only)', '',
        '```json', json.dumps(state or {'status':'unknown','num_iter':None}, ensure_ascii=False, indent=2), '```', '',
        'Missing num_iter is unknown, not inferred as zero. Convergence, complete products, and fit acceptance are distinct.', '',
        '## Trial files', '', '- [selection](records/selection/): sealed choice, figures, and provenance.',
        '- [results](records/results/): result snapshots, observations, and hypotheses.',
        '- [Decision trajectory](../index.html): initial and all trials.',
        '- [interface](interface/): original interface inputs and outputs.', '- [wannier](wannier/): actual execution directory.',
        '- [comparison](comparison/): same-k fit evidence.']
    for destination, source, relative in plans:
        if destination.parent == trial:
            lines.append(f'- [{destination.name}]({destination.name}) → `{relative}`')
    lines += ['', '## DFT band figures', '']
    lines += [f'- [{name}](../../02_band/{name})' for name in band_images] or ['No figures available yet.']
    lines += ['', '## Missing items', '']
    lines += [f'- `{name}`' for name in missing] if missing else ['Display inventory complete; scientific acceptance remains separate.']
    write_readme(trial/'README.md', '\n'.join(lines)+'\n')
    write_readme(case/'README.md', case_readme(case))
    return dict(status='incomplete' if missing else 'display_complete', paths=trial_paths(case, trial),
        missing=missing, links=[dict(path=str(d), target=r) for d,_,r in plans],
        recorded_wannier_state=state, accepted=False,
        scope='Human navigation only; no new calculations or scientific acceptance.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('init'); p.add_argument('--case-dir', required=True)
    p.add_argument('--scf-source', required=True); p.add_argument('--band-source', required=True)
    for name in ('new-trial', 'publish'):
        p = sub.add_parser(name); p.add_argument('--case-dir', required=True); p.add_argument('--trial-id', required=True)
    args = parser.parse_args()
    try:
        if args.command == 'init': result = init(args.case_dir, args.scf_source, args.band_source)
        elif args.command == 'new-trial': result = new_trial(args.case_dir, args.trial_id)
        else: result = publish(args.case_dir, args.trial_id)
        print(json.dumps(result, ensure_ascii=False, indent=2, allow_nan=False))
        return 0
    except (ValueError, OSError, KeyError, TypeError) as error:
        parser.exit(2, str(error)+'\n')


if __name__ == '__main__':
    raise SystemExit(main())
